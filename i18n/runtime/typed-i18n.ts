import type { ConflictReport } from '../../shared/runtime/conflicts'
import { isPlainObject } from './merge'

export function collectI18nLeafKeys(
    obj: Record<string, unknown>,
    prefix = '',
    keys: string[] = []
): string[] {
    for (const [key, value] of Object.entries(obj)) {
        const path = prefix ? `${prefix}.${key}` : key
        if (isPlainObject(value)) {
            collectI18nLeafKeys(value, path, keys)
        } else {
            keys.push(path)
        }
    }
    return keys
}

/**
 * @param schemaLocale - Locale dont le JSON généré (`<code>.json`, à côté du
 *   `.d.ts`) sert de schéma à `DefineLocaleMessage`.
 */
export function generateTypedI18nDts(
    keys: Iterable<string>,
    schemaLocale?: string
): string {
    const unique = [...new Set(keys)].sort()
    const unionMembers = unique
        .map((k) => `  | '${k.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`)
        .join('\n')

    // Une signature d'index ne peut pas porter une union de littéraux : on
    // s'appuie sur la structure réelle du JSON, comme recommandé par vue-i18n.
    const schema = schemaLocale
        ? [
              `type DomainI18nSchema = typeof import('./${schemaLocale}.json')`,
              '',
              "declare module 'vue-i18n' {",
              '  export interface DefineLocaleMessage extends DomainI18nSchema {}',
              '}',
              '',
          ]
        : []

    return [
        '// Auto-generated by domain-i18n. Do not edit manually.',
        '',
        'type DomainI18nKey =',
        unionMembers || '  | never',
        '',
        ...schema,
        'export type { DomainI18nKey }',
        '',
    ].join('\n')
}

export interface I18nKeyTracker {
  track(key: string, source: string): ConflictReport | null
}

export function createI18nKeyTracker(): I18nKeyTracker {
  const seen = new Map<string, string>()

  return {
    track(key: string, source: string): ConflictReport | null {
      const prev = seen.get(key)
      if (prev && prev !== source) {
        return {
          kind: 'i18n-key',
          message: `Clé "${key}" écrasée : "${prev}" → "${source}"`,
        }
      }
      if (!prev) seen.set(key, source)
      return null
    },
  }
}
