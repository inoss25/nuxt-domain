import { mkdirSync } from 'node:fs'
import { resolve, relative } from 'node:path'
import type { NuxtPage } from '@nuxt/schema'
import { writeIfChanged } from '../../shared/runtime/fs'
import { toPosixPath } from '../../shared/runtime/paths'
import { flattenRouteMap, type RouteEntry } from './utils'

/* ------------------------------------------------------------------ */
/*  Markdown doc                                                        */
/* ------------------------------------------------------------------ */

function generateMarkdown(
    allRows: Array<{ path: string; name: string; file?: string }>,
    rootDir: string
): string {
    const tableLines = allRows.map((r) => {
        const fp = r.file ? toPosixPath(relative(rootDir, r.file)) : ''
        const safeName = (r.name || '—').replace(/\|/g, '\\|')
        return `| \`${r.path}\` | ${safeName} | \`${fp}\` |`
    })

    return [
        '# Routes (domain-pages)',
        '',
        '_Fichier généré automatiquement par le module `domain-pages` — ne pas modifier à la main._',
        '',
        '| Chemin | Nom | Fichier source |',
        '| --- | --- | --- |',
        ...tableLines,
        '',
        `**Total :** ${allRows.length} route(s).`,
        '',
    ].join('\n')
}

/* ------------------------------------------------------------------ */
/*  JSON route map                                                      */
/* ------------------------------------------------------------------ */

function generateRouteMapJson(
    allRows: Array<{ path: string; name: string; file?: string }>
): string {
    const entries = allRows.map((r) => ({
        path: r.path,
        name: r.name,
        file: r.file ? toPosixPath(r.file) : undefined,
    }))
    return JSON.stringify(entries, null, 2) + '\n'
}

/* ------------------------------------------------------------------ */
/*  Typed route names (typed-router.d.ts)                              */
/* ------------------------------------------------------------------ */

function generateTypedRoutes(
    allRouteNames: Array<{ path: string; name: string }>
): string {
    const uniqueNames = [...new Set(allRouteNames.map((r) => r.name).filter(Boolean))]
    uniqueNames.sort()

    const unionMembers = uniqueNames
        .map((n) => `  | '${n.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`)
        .join('\n')

    // Type global seulement : vue-router n'expose pas d'interface à étendre pour
    // les noms (le typage natif passe par `experimental.typedPages` de Nuxt).
    return [
        '// This file is auto-generated by the domain-pages module. Do not edit manually.',
        '',
        'declare global {',
        '  type DomainPagesRouteName =',
        (unionMembers || '  | never').replace(/^/gm, '  '),
        '}',
        '',
        'export {}',
        '',
    ].join('\n')
}

/* ------------------------------------------------------------------ */
/*  Public entry point                                                  */
/* ------------------------------------------------------------------ */

export interface RouteDocContext {
    rootDir: string
    routeDoc: { enabled: boolean; outDir: string; fileName: string }
    routeMap: Map<string, NuxtPage>
    allRouteNames: Array<{ path: string; name: string }>
    /** Routes déjà aplaties par `generateDomainRoutes` (sinon recalculées). */
    entries?: RouteEntry[]
    debugLog: (...args: any[]) => void
}

export function writeRouteDoc(ctx: RouteDocContext): void {
    const { rootDir, routeDoc, routeMap, allRouteNames, debugLog } = ctx

    if (!routeDoc.enabled) return

    const allRows = [...(ctx.entries ?? flattenRouteMap(routeMap))]
    allRows.sort((a, b) =>
        a.path === b.path
            ? (a.name || '').localeCompare(b.name || '')
            : a.path.localeCompare(b.path)
    )

    const outDirAbs = resolve(rootDir, routeDoc.outDir)
    mkdirSync(outDirAbs, { recursive: true })

    // 1. Markdown doc
    const md = generateMarkdown(allRows, rootDir)
    const outFile = resolve(outDirAbs, routeDoc.fileName)
    writeIfChanged(outFile, md)
    debugLog('📝 [domain-pages] route doc écrit:', {
        file: toPosixPath(relative(rootDir, outFile)),
    })

    // 2. JSON route map
    const jsonPath = resolve(outDirAbs, 'route-map.json')
    writeIfChanged(jsonPath, generateRouteMapJson(allRows))
    debugLog('📦 [domain-pages] route-map.json écrit:', {
        file: toPosixPath(relative(rootDir, jsonPath)),
    })

    // 3. Typed routes (typed-router.d.ts)
    const typedPath = resolve(outDirAbs, 'typed-router.d.ts')
    writeIfChanged(typedPath, generateTypedRoutes(allRouteNames))
    debugLog('🔒 [domain-pages] typed-router.d.ts écrit:', {
        file: toPosixPath(relative(rootDir, typedPath)),
    })
}
